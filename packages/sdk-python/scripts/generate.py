"""Generate typed SDK methods from Bulkgrid's committed public OpenAPI contract.

Run from any directory; --check detects drift without writing files.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parents[1]
SPEC = next(
    p
    for p in [
        ROOT / "apps/docs/api-reference/openapi.json",
        ROOT / "openapi/bulkgrid.openapi.json",
        ROOT / "docs/api-reference/openapi.json",
    ]
    if p.exists()
)
spec = json.loads(SPEC.read_text())

# Public Python names deliberately mirror the TypeScript resource layout.
names = {
    "analyzeSource": "index.sources.analyze",
    "getSourceAnalysis": "index.sources.get_analysis",
    "search": "search",
    "indexSearch": "index.search",
    "createExtractRun": "extract",
    "createCrawlRun": "crawl",
    "createMapRun": "map",
    "createDeepCrawlRun": "deep_crawl",
    "listRuns": "runs.list",
    "createRun": "runs.create",
    "getRun": "runs.get",
    "deleteRun": "runs.delete",
    "cancelRun": "runs.cancel",
    "retryRun": "runs.retry",
    "listRunResults": "runs.results",
    "getRunResultContent": "runs.get_result_content",
    "getRunResultScreenshot": "runs.get_result_screenshot",
}


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def pascal(name):
    return "".join(p[0].upper() + p[1:] for p in re.split(r"[^a-zA-Z0-9]", name) if p)


lines = [
    "# Generated by scripts/generate.py. Do not edit.",
    "from __future__ import annotations",
    "from typing import Literal, Union",
    "from typing_extensions import NotRequired, TypedDict, TypeAlias",
    "",
    'JSONValue: TypeAlias = Union[None, bool, int, float, str, list["JSONValue"], dict[str, "JSONValue"]]',
    "",
]
cache = {}


def annotation(schema, name):
    if "$ref" in schema:
        target = spec["components"]["schemas"][schema["$ref"].split("/")[-1]]
        # OpenAPI recursive component schemas represent arbitrary JSON values.
        if any("$ref" in json.dumps(part) for part in target.get("anyOf", [])):
            return "JSONValue"
        return annotation(target, name)
    key = json.dumps(schema, sort_keys=True)
    if key in cache:
        return cache[key]
    if "enum" in schema:
        vals = [repr(v) for v in schema["enum"] if v is not None]
        result = "Literal[" + ", ".join(vals) + "]" if vals else "None"
    elif "anyOf" in schema or "oneOf" in schema:
        parts = schema.get("anyOf", schema.get("oneOf"))
        result = (
            "Union["
            + ", ".join(annotation(p, p.get("title", name + str(i))) for i, p in enumerate(parts))
            + "]"
        )
    elif schema.get("type") == "object" and schema.get("properties"):
        fields = []
        for prop, value in schema["properties"].items():
            if not prop.isidentifier():
                raise ValueError(f"Unsupported Python field: {prop}")
            kind = annotation(value, name + pascal(prop))
            if prop not in schema.get("required", []):
                kind = f"NotRequired[{kind}]"
            fields.append(f"    {prop}: {kind}")
        lines.extend([f"class {name}(TypedDict):", *fields, "", ""])
        result = name
    elif schema.get("type") == "array":
        result = f"list[{annotation(schema.get('items', {}), name + 'Item')}]"
    elif schema.get("type") == "object":
        value = schema.get("additionalProperties", {})
        result = f"dict[str, {annotation(value if isinstance(value, dict) else {}, name + 'Value')}]"
    else:
        result = {
            "string": "str",
            "number": "float",
            "integer": "int",
            "boolean": "bool",
            "null": "None",
        }.get(schema.get("type"), "object")
    if schema.get("nullable") and result not in {"None", "object"}:
        result = f"Union[{result}, None]"
    cache[key] = result
    return result


def named(schema, name):
    kind = annotation(schema, name)
    if kind != name:
        lines.extend([f"{name}: TypeAlias = {kind}", ""])
    return name


operations = []
for path, methods in spec["paths"].items():
    for verb, op in methods.items():
        op_id = op["operationId"]
        name = names.get(op_id)
        if not name:
            for group in ["sources", "collections"]:
                if op_id.startswith(group):
                    name = "index." + group + "." + snake(op_id[len(group) :])
                    break
        if not name:
            continue
        prefix = pascal(name)
        body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
        if body and name in ["crawl", "deep_crawl", "extract", "map"]:
            body = dict(
                body,
                properties={k: v for k, v in body["properties"].items() if k != "type"},
                required=[k for k in body.get("required", []) if k != "type"],
            )
        body_type = named(body, prefix + "Input") if body else None
        query_params = [p for p in op.get("parameters", []) if p["in"] == "query"]
        # Screenshot download uses a distinct method with a bytes return type.
        if name == "runs.get_result_screenshot":
            query_params = []
        query_type = (
            named(
                {
                    "type": "object",
                    "properties": {p["name"]: p["schema"] for p in query_params},
                    "required": [p["name"] for p in query_params if p.get("required")],
                },
                prefix + "Query",
            )
            if query_params
            else None
        )
        response = next(v for k, v in op["responses"].items() if k.startswith("2"))
        content = response.get("content", {})
        response_type = (
            named(content["application/json"]["schema"], prefix + "Response")
            if "application/json" in content
            else "str"
        )
        operations.append(
            dict(
                name=name,
                path=path,
                verb=verb.upper(),
                body=body_type,
                query=query_type,
                required_query=any(p.get("required") for p in query_params),
                response=response_type,
                mode="text" if response_type == "str" else "json",
                description=op.get("summary", name),
            )
        )
operations.append(
    dict(
        next(op for op in operations if op["name"] == "runs.get_result_screenshot"),
        name="runs.download_result_screenshot",
        response="bytes",
        mode="bytes",
    )
)

header = "# Generated by scripts/generate.py. Do not edit.\nfrom __future__ import annotations\n\nfrom typing import cast\nfrom typing_extensions import Self\nimport httpx\n\nfrom . import types\nfrom ._transport import SyncTransport, AsyncTransport, path_id\n\n"
clients = [header]
for asynchronous in [False, True]:
    pre = "Async" if asynchronous else ""
    transport = pre + "Transport" if asynchronous else "SyncTransport"
    await_ = "await " if asynchronous else ""
    def_ = "async def" if asynchronous else "def"
    for group in ["index.sources", "index.collections", "index", "runs", ""]:
        classname = pre + (pascal(group) if group else "BulkgridClient")
        clients.append(f"class {classname}" + (f"({transport})" if not group else "") + ":\n")
        if group:
            clients.append(
                f"    def __init__(self, transport: {transport}) -> None:\n        self._transport = transport\n\n"
            )
            if group == "index":
                clients.append(
                    f"        self.sources = {pre}IndexSources(transport)\n        self.collections = {pre}IndexCollections(transport)\n\n"
                )
        else:
            ht = "AsyncBaseTransport" if asynchronous else "BaseTransport"
            clients.append(f"""    def __init__(self, *, api_key: str, base_url: str = "https://bulkgrid.com", timeout: float = 60.0,
                 transport: httpx.{ht} | None = None) -> None:
        super().__init__(api_key=api_key, base_url=base_url, timeout=timeout, transport=transport)
        self.index = {pre}Index(self)
        self.runs = {pre}Runs(self)

    {def_} __{"a" if asynchronous else ""}enter__(self) -> Self:
        return self

""")
        for op in operations:
            opgroup, _, method = op["name"].rpartition(".")
            if opgroup != group:
                continue
            args = ["self"]
            for param in re.findall(r"{(\w+)}", op["path"]):
                args.append(f"{snake(param)}: str")
            if op["body"]:
                args.append("input: types." + op["body"] + (" | None = None" if method == "retry" else ""))
            if op["query"]:
                args.append(
                    "query: types." + op["query"] + ("" if op["required_query"] else " | None = None")
                )
            result = op["response"] if op["response"] in ["str", "bytes"] else "types." + op["response"]
            path = re.sub(r"{(\w+)}", lambda m: "{path_id(" + snake(m[1]) + ")}", op["path"])
            path = ("f" if "{" in path else "") + repr(path)
            kwargs = []
            if op["body"]:
                body = "input"
                if not group and method in ["crawl", "extract", "deep_crawl", "map"]:
                    body = '{**input, "type": ' + repr(method) + "}"
                elif method == "retry":
                    body = "input if input is not None else {}"
                kwargs.append("body=" + body)
            if op["query"]:
                kwargs.append("query=query")
            if op["mode"] != "json":
                kwargs.append("mode=" + repr(op["mode"]))
            if op["mode"] == "bytes":
                kwargs.append('query={"download": True}')
            suffix = (", " + ", ".join(kwargs)) if kwargs else ""
            target = "self._transport" if group else "self"
            clients.append(
                f'    {def_} {method}({", ".join(args)}) -> {result}:\n        """{op["description"]}."""\n        return cast({result}, {await_}{target}._request({op["verb"]!r}, {path}{suffix}))\n\n'
            )
        if group == "index.collections":
            clients.append(f'''    {def_} add_source(self, collection_id: str, source_id: str) -> types.IndexCollectionsUpdateRulesResponse:
        """Include an entire source in a collection."""
        return {await_}self.update_rules(collection_id, {{"add": [{{"action": "include", "target": "source", "source_id": source_id, "target_id": source_id}}]}})

    {def_} remove_source(self, collection_id: str, source_id: str) -> types.IndexCollectionsUpdateRulesResponse:
        """Remove all collection rules for this source, matching the TypeScript SDK."""
        current = {await_}self.rules(collection_id)
        return {await_}self.update_rules(collection_id, {{"remove": [
            {{"action": rule["action"], "target": rule["target"], "source_id": rule["source_id"], "target_id": rule["target_id"]}}
            for rule in current["rules"] if rule["source_id"] == source_id
        ]}})

''')

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
# Ruff formatting is deterministic and kept out of the runtime dependency set.

for name, text in {"types.py": "\n".join(lines), "_client.py": "".join(clients)}.items():
    text = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(PACKAGE / "src/bulkgrid" / name)],
        input=text,
        text=True,
        capture_output=True,
        check=True,
    ).stdout
    target = PACKAGE / "src/bulkgrid" / name
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit(f"{target.name} is stale; run python packages/sdk-python/scripts/generate.py")
    else:
        target.write_text(text)
print(f"{'Checked' if args.check else 'Generated'} {len(operations)} methods for each client.")
